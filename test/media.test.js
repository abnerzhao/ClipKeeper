const { test } = require('node:test')
const assert = require('node:assert/strict')
const os = require('node:os')
const fs = require('node:fs/promises')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { path: ffmpeg } = require('@ffmpeg-installer/ffmpeg')
const { exportCut, discover, suggestName, preview } = require('../media')
const { Library } = require('../library')

test('导入去重、备注和粗剪范围恢复、移出仅影响素材库', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'clipkeeper-lib-'))
  t.after(() => fs.rm(dir, { recursive:true, force:true }))
  const file = path.join(dir, '中文 素材.mp4')
  await fs.writeFile(file, 'original')
  const { files } = await discover([dir, file])
  assert.deepEqual(files, [await fs.realpath(file)])
  const lib = new Library(dir)
  const [item] = lib.add(files)
  assert.equal(lib.add(files).length, 0)
  lib.update(item.id, { note:'海边/日落', start:1, end:2 })
  assert.equal(suggestName(file, '海边/日落'), '中文 素材_海边_日落.mp4')
  assert.deepEqual(new Library(dir).get(item.id), lib.get(item.id))
  lib.remove(item.id)
  assert.equal(await fs.readFile(file, 'utf8'), 'original')
})

test('真实音视频：另存、同名保护、失败回滚、兼容预览和覆盖', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'clipkeeper-media-'))
  t.after(() => fs.rm(dir, { recursive:true, force:true }))
  const source = path.join(dir, '原片.mov'), target = path.join(dir, '导出.mp4')
  execFileSync(ffmpeg, ['-loglevel','error','-f','lavfi','-i','testsrc2=size=160x90:rate=25',
    '-f','lavfi','-i','sine=frequency=440','-t','3','-c:v','libx264','-c:a','aac',source])
  const raw = await fs.readFile(source)
  const cut = { source, target, start:0.4, end:1.6, overwrite:false }
  await exportCut(cut)
  const inspect = file => {
    try { execFileSync(ffmpeg, ['-hide_banner','-i',file], { stdio:'pipe' }) }
    catch (e) { return e.stderr.toString() }
  }
  const result = inspect(target)
  assert.match(result, /Duration: 00:00:01\.2/)
  assert.match(result, /Video: h264/)
  assert.match(result, /Audio: aac/)
  assert.deepEqual(await fs.readFile(source), raw)
  const saved = await fs.readFile(target)
  await assert.rejects(exportCut(cut), /同名文件/)
  assert.deepEqual(await fs.readFile(target), saved)
  await assert.rejects(exportCut({ ...cut, target:source, overwrite:true, signal:AbortSignal.abort() }))
  assert.deepEqual(await fs.readFile(source), raw)
  await assert.rejects(exportCut({ ...cut, target:source, overwrite:true, start:9, end:11 }))
  assert.deepEqual(await fs.readFile(source), raw)
  const proxy = path.join(dir, 'proxy.mp4')
  await preview(source, proxy)
  assert.match(inspect(proxy), /Duration: 00:00:03/)
  await exportCut({ ...cut, target:source, overwrite:true })
  assert.match(inspect(source), /Duration: 00:00:01\.2/)
  assert.equal((await fs.readdir(dir)).some(f => f.startsWith('.clipkeeper-')), false)
})

test('旧素材按所在目录归组，重复导入父目录后保留备注并恢复完整目录树', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'clipkeeper-tree-'))
  t.after(() => fs.rm(dir, { recursive:true, force:true }))
  const project = path.join(dir, '旅行')
  const file = path.join(project, '杭州', '素材', 'A.mp4')
  const other = path.join(dir, '其他', '素材', 'A.mp4')
  const old = { id:'old', path:file, name:'A.mp4', note:'夜景', start:1, end:2 }
  await fs.writeFile(path.join(dir, 'library.json'), JSON.stringify([old]))
  const lib = new Library(dir)
  lib.add([other])
  assert.notEqual(lib.rows()[0].folders[0].path, lib.rows()[1].folders[0].path)
  assert.deepEqual(lib.add([file], '', [project]), [])
  const [restored] = new Library(dir).rows()
  assert.deepEqual(restored.folders.map(f => f.name), ['旅行','杭州','素材'])
  assert.equal(restored.note, old.note)
  assert.equal(restored.id, old.id)
})
